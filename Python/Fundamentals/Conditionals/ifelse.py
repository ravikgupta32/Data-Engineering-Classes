#If-else control statement
x= 13
if(x==10):
    print ('x is',x)
else:
    print('x is',x)

#If else and elif
x=110;
if (x==10):
    print('X is 10')
elif(x>100):
    print('X is greater than 100')
else:
    print('X is not 10')

#Nested if else
x=210;
if (x==10):
    print('X is 10')
elif(x>100):
    if(x>100 and x<200):
        print('Between 100 & 200')
    else:
        print('Greater than 200')
else:
    print('X is not 10')